package dev.davamu.filebotpro.hash;

import java.io.BufferedWriter;
import java.io.Closeable;
import java.io.File;
import java.io.FileOutputStream;
import java.io.IOException;
import java.io.OutputStreamWriter;
import java.io.PrintWriter;
import java.nio.charset.Charset;
import java.nio.file.Path;
import java.util.Date;

import dev.davamu.filebotpro.Settings;
import dev.davamu.filebotpro.util.FileUtilities;

public class VerificationFileWriter implements Closeable {

	protected PrintWriter out;
	protected VerificationFormat format;

	// SFV files are conventionally CRLF, md5sum / sha1sum style files are LF
	protected String lineSeparator;

	public VerificationFileWriter(File file, VerificationFormat format, Charset charset) throws IOException {
		this(new PrintWriter(new BufferedWriter(new OutputStreamWriter(new FileOutputStream(file), charset)), false), format, charset);
	}

	public VerificationFileWriter(PrintWriter out, VerificationFormat format, Charset charset) {
		this.out = out;
		this.format = format;
		this.lineSeparator = format instanceof SfvFormat ? "\r\n" : "\n";

		// start by printing the file header
		writeHeader(charset);
	}

	protected void writeHeader(Charset charset) {
		// md5sum / sha1sum only ignore # comment lines
		String comment = format instanceof SfvFormat ? ";" : "#";

		writeLine(String.format("%s Generated by %s %s on %tF at %<tT", comment, Settings.getApplicationName(), Settings.getApplicationVersion(), new Date()));
		if (format instanceof SfvFormat) {
			writeLine(String.format("%s charset=%s", comment, charset));
		}
		writeLine(comment);
	}

	public void write(String path, String hash) {
		writeLine(format.format(path, hash));
	}

	protected void writeLine(String line) {
		out.write(line);
		out.write(lineSeparator);
	}

	@Override
	public void close() throws IOException {
		out.close();

		// PrintWriter swallows I/O errors
		if (out.checkError()) {
			throw new IOException("Failed to write verification file");
		}
	}

	/**
	 * Path of the given file relative to the folder of the verification file, with / separators. Files on a different
	 * file system root can only be referenced by their absolute path.
	 */
	public static String getRelativePath(File file, File folder) {
		Path path = file.toPath().toAbsolutePath().normalize();
		Path base = folder.toPath().toAbsolutePath().normalize();

		if (path.getRoot() == null || !path.getRoot().equals(base.getRoot())) {
			return FileUtilities.normalizePathSeparators(path.toString());
		}
		return FileUtilities.normalizePathSeparators(base.relativize(path).toString());
	}

}
